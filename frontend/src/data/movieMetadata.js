export function getMovieMetadata(id) {
  // Try exact key match first (slug)
  if (MOVIE_METADATA[id]) return MOVIE_METADATA[id];
  // Fallback: match by title (case-insensitive)
  const match = Object.values(MOVIE_METADATA).find((m) =>
    m.title.toLowerCase() === String(id).toLowerCase()
  );
  return match || null;
}

