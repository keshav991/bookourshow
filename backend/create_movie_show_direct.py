from app.database import SessionLocal, engine
from sqlalchemy import text, inspect

db = SessionLocal()

# Direct SQL - bypass any ORM logic
print("Creating movie_show table...")
create_movie_show_sql = """CREATE TABLE IF NOT EXISTS public.movie_show (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id bigint NOT NULL REFERENCES public.movies(id) ON DELETE CASCADE,
    screen_id bigint NOT NULL REFERENCES public.screens(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'NOT_STARTED',
    created_at timestamptz NOT NULL DEFAULT now()
);"""

try:
    # Use engine directly to execute raw SQL
    with db.begin():
        result = db.execute(text(create_movie_show_sql))
        print("Table creation SQL executed")
    
    # Verify table exists immediately
    verify_query = "SELECT EXISTS(SELECT 1 FROM information_schema.tables WHERE table_name='movie_show' AND table_schema='public');"
    res = db.execute(text(verify_query))
    exists = res.fetchone()[0]
    print(f"Table exists check: {exists}")
    
except Exception as e:
    print(f"Error: {e}")

db.close()
