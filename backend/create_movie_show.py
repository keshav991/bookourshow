from app.database import SessionLocal, engine
from sqlalchemy import text

db = SessionLocal()

# Create movie_show table if it doesn't exist
create_movie_show_sql = """
CREATE TABLE IF NOT EXISTS public.movie_show (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id bigint NOT NULL REFERENCES public.movies(id) ON DELETE CASCADE,
    screen_id bigint NOT NULL REFERENCES public.screens(id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'NOT_STARTED',
    created_at timestamptz NOT NULL DEFAULT now()
);
"""

try:
    res = db.execute(text(create_movie_show_sql))
    print("Movie show table created successfully")
except Exception as e:
    print(f"Error creating table: {e}")

db.close()
