-- Normalize the existing development schema to the canonical constraints.
-- Run only after 000_reset_development_data.sql on the existing development project,
-- or after 001_create_schema.sql on a fresh project. No Supabase Auth objects touched.
-- STRUCTURAL REPLACEMENT: this migration drops/recreates legacy application constraints
-- and replaces public serial sequences with identity generators. It is guarded below
-- to require empty application tables; it does not delete application rows.
BEGIN;

DO $$
DECLARE t text; has_rows boolean;
BEGIN
    FOREACH t IN ARRAY ARRAY['cities','theatres','screens','seats','movies','shows','show_seats','bookings','booking_seats','payments'] LOOP
        EXECUTE format('SELECT EXISTS (SELECT 1 FROM public.%I)', t) INTO has_rows;
        IF has_rows THEN
            RAISE EXCEPTION 'public.% is not empty. Review and run the development-only reset migration before structural normalization.', t;
        END IF;
    END LOOP;
    IF NOT EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'btree_gist') THEN
        RAISE EXCEPTION 'Required extension btree_gist is unavailable in this PostgreSQL installation.';
    END IF;
    IF NOT has_database_privilege(current_user, current_database(), 'CREATE') THEN
        RAISE EXCEPTION 'Role % lacks database CREATE privilege required to install btree_gist.', current_user;
    END IF;
END $$;
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Columns added to the audited development schema for same-screen and same-show keys.
ALTER TABLE public.show_seats ADD COLUMN IF NOT EXISTS screen_id bigint;
