ALTER TABLE public.bookings ADD COLUMN IF NOT EXISTS expires_at timestamptz;
ALTER TABLE public.payments ADD COLUMN IF NOT EXISTS idempotency_key text;

-- Safe because this migration is preceded by the explicitly destructive dev reset.
UPDATE public.show_seats ss SET screen_id = sh.screen_id
FROM public.shows sh WHERE sh.id = ss.show_id AND ss.screen_id IS NULL;
UPDATE public.booking_seats bs SET show_id = b.show_id
FROM public.bookings b WHERE b.id = bs.booking_id AND bs.show_id IS NULL;
ALTER TABLE public.show_seats ALTER COLUMN screen_id SET NOT NULL;
ALTER TABLE public.booking_seats ALTER COLUMN show_id SET NOT NULL;

-- Standardize integer IDs on identity columns after the dev reset. Old serial defaults
-- and their owned sequences are removed only from the listed public application tables.
DO $$
DECLARE t text; seq_name text;
BEGIN
    FOREACH t IN ARRAY ARRAY['cities','theatres','screens','seats','movies','shows','show_seats','bookings','booking_seats','payments'] LOOP
        IF (SELECT is_identity = 'NO' FROM information_schema.columns
            WHERE table_schema='public' AND table_name=t AND column_name='id') THEN
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id DROP DEFAULT', t);
            seq_name := pg_get_serial_sequence('public.' || quote_ident(t), 'id');
            IF seq_name IS NOT NULL THEN
                EXECUTE format('ALTER SEQUENCE %s OWNED BY NONE', seq_name);
                EXECUTE format('DROP SEQUENCE %s', seq_name);
            END IF;
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
        END IF;
    END LOOP;
END $$;

