-- BookOurShow database foundation. Run only in the intended development project.
-- This migration never creates, alters, or drops objects in Supabase-managed schemas.
BEGIN;

CREATE TABLE IF NOT EXISTS public.cities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    state text NOT NULL,
    country text NOT NULL DEFAULT 'India',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_cities_name_state_country UNIQUE (name, state, country)
);

CREATE TABLE IF NOT EXISTS public.movies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    description text,
    poster_url text,
    backdrop_url text,
    duration_minutes integer,
    release_date date,
    language text NOT NULL DEFAULT 'Hindi',
    certification text,
    status text NOT NULL DEFAULT 'UPCOMING',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_movies_title UNIQUE (title),
    CONSTRAINT ck_movies_duration_positive CHECK (duration_minutes IS NULL OR duration_minutes > 0),
    CONSTRAINT ck_movies_status CHECK (status IN ('UPCOMING', 'NOW_SHOWING', 'ENDED'))
);

-- `profiles` is application-owned, but its user IDs belong to Supabase Auth.
CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name text,
    role text NOT NULL DEFAULT 'customer',
    created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.theatres (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id bigint NOT NULL REFERENCES public.cities(id) ON DELETE RESTRICT,
    name text NOT NULL,
    address text NOT NULL,
    latitude numeric,
    longitude numeric,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_theatres_city_name_address UNIQUE (city_id, name, address)
);

CREATE TABLE IF NOT EXISTS public.screens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_id bigint NOT NULL REFERENCES public.theatres(id) ON DELETE CASCADE,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_screens_theatre_name UNIQUE (theatre_id, name)
);

CREATE TABLE IF NOT EXISTS public.seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id bigint NOT NULL REFERENCES public.screens(id) ON DELETE CASCADE,
    row_label text NOT NULL,
    seat_number integer NOT NULL CHECK (seat_number > 0),
    seat_type text NOT NULL DEFAULT 'REGULAR',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_seats_screen_row_number UNIQUE (screen_id, row_label, seat_number),
    CONSTRAINT uq_seats_id_screen UNIQUE (id, screen_id),
    CONSTRAINT ck_seats_type CHECK (seat_type IN ('REGULAR', 'PREMIUM', 'RECLINER'))
);

CREATE TABLE IF NOT EXISTS public.shows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id bigint NOT NULL REFERENCES public.movies(id) ON DELETE RESTRICT,
    screen_id bigint NOT NULL REFERENCES public.screens(id) ON DELETE RESTRICT,
    start_time timestamptz NOT NULL,
    end_time timestamptz NOT NULL,
    language text NOT NULL DEFAULT 'Hindi',
    format text NOT NULL DEFAULT '2D',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_shows_id_screen UNIQUE (id, screen_id),
    CONSTRAINT uq_shows_screen_start UNIQUE (screen_id, start_time),
    CONSTRAINT ck_shows_time CHECK (end_time > start_time),
    CONSTRAINT ck_shows_format CHECK (format IN ('2D', '3D', 'IMAX', '4DX'))
);

CREATE TABLE IF NOT EXISTS public.bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    show_id bigint NOT NULL REFERENCES public.shows(id) ON DELETE RESTRICT,
    booking_reference text NOT NULL UNIQUE,
    total_amount numeric(12, 2) NOT NULL CHECK (total_amount >= 0),
    status text NOT NULL DEFAULT 'PENDING',
    idempotency_key text,
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_bookings_id_show UNIQUE (id, show_id),
    CONSTRAINT uq_bookings_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_bookings_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED'))
);

CREATE TABLE IF NOT EXISTS public.show_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id bigint NOT NULL,
    screen_id bigint NOT NULL,
    seat_id bigint NOT NULL,
    booking_id bigint,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    status text NOT NULL DEFAULT 'AVAILABLE',
    locked_by uuid REFERENCES auth.users(id) ON DELETE RESTRICT,
    locked_until timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_show_seats_show_screen FOREIGN KEY (show_id, screen_id)
        REFERENCES public.shows(id, screen_id) ON DELETE CASCADE,
    CONSTRAINT fk_show_seats_seat_screen FOREIGN KEY (seat_id, screen_id)
        REFERENCES public.seats(id, screen_id) ON DELETE RESTRICT,
    CONSTRAINT fk_show_seats_booking_show FOREIGN KEY (booking_id, show_id)
        REFERENCES public.bookings(id, show_id) ON DELETE RESTRICT,
    CONSTRAINT uq_show_seats_show_seat UNIQUE (show_id, seat_id),
    CONSTRAINT uq_show_seats_id_show UNIQUE (id, show_id),
    CONSTRAINT ck_show_seats_status CHECK (status IN ('AVAILABLE', 'LOCKED', 'BOOKED')),
    CONSTRAINT ck_show_seats_lock_state CHECK (
        (status = 'AVAILABLE' AND locked_by IS NULL AND locked_until IS NULL AND booking_id IS NULL) OR
        (status = 'LOCKED' AND locked_by IS NOT NULL AND locked_until IS NOT NULL) OR
        (status = 'BOOKED' AND locked_by IS NULL AND locked_until IS NULL AND booking_id IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.booking_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL,
    show_id bigint NOT NULL,
    show_seat_id bigint NOT NULL,
    price numeric(12, 2) NOT NULL CHECK (price >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_booking_seats_booking_show FOREIGN KEY (booking_id, show_id)
        REFERENCES public.bookings(id, show_id) ON DELETE CASCADE,
    CONSTRAINT fk_booking_seats_show_seat_show FOREIGN KEY (show_seat_id, show_id)
        REFERENCES public.show_seats(id, show_id) ON DELETE RESTRICT,
    CONSTRAINT uq_booking_seats_booking_show_seat UNIQUE (booking_id, show_seat_id)
);

CREATE TABLE IF NOT EXISTS public.payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES public.bookings(id) ON DELETE RESTRICT,
    provider text NOT NULL DEFAULT 'RAZORPAY',
    provider_order_id text UNIQUE,
    provider_payment_id text UNIQUE,
    amount numeric(12, 2) NOT NULL CHECK (amount > 0),
    status text NOT NULL DEFAULT 'CREATED',
    idempotency_key text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_payments_booking_idempotency UNIQUE (booking_id, idempotency_key),
    CONSTRAINT ck_payments_status CHECK (status IN ('CREATED', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED'))
);

COMMIT;
