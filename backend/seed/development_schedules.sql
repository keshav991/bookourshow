-- BookOurShow development show schedules, November 11–17, 2026.
-- Review and run manually in Supabase SQL Editor. This file has NOT been executed.
-- It inserts only rows into public.shows and public.show_seats. It does not
-- create/alter schema, change existing rows, or touch seats/bookings/payments.
--
-- Expected first run against the currently inspected database: 21 shows and
-- 420 show_seats (one screen, three slots/day, 20 seats/show); 3 shows per
-- movie, 3 shows/day, and no screens skipped. Each movie is resolved by its
-- exact title. Local start times are 10:00, 14:00, and 18:00 Asia/Kolkata.
-- Four-hour slot spacing accommodates the longest current movie (181 min)
-- plus a 30-minute cleaning buffer. All new formats are 2D, which the existing
-- screen already uses. Prices: Regular ₹180, Premium ₹250, Recliner ₹350;
-- evening shows add ₹30. New seats use the existing AVAILABLE status.
--
-- Reruns take the same advisory transaction lock and reuse exact show slots.
-- The live schema has no unique key for a show slot; this script intentionally
-- does not use ON CONFLICT for shows. The advisory lock serializes this script,
-- deterministic (screen_id,start_time) matching provides idempotency, and
-- mismatched/duplicate slot rows cause a safe exception. The existing unique
-- (show_id,seat_id) key is verified before ON CONFLICT is used for show_seats.

BEGIN;

SELECT pg_advisory_xact_lock(hashtextextended('bookourshow-development-schedules-20261111', 0));

DO $$
DECLARE
    expected_movies TEXT[] := ARRAY[
        'Interstellar', 'Inception', 'Avengers: Endgame', 'Dune: Part Two',
        'Deadpool & Wolverine', 'Oppenheimer', 'Gladiator II'
    ];
    required_pk RECORD;
    required_fk RECORD;
    required_unique RECORD;
    source_attnum SMALLINT;
    target_attnum SMALLINT;
    constraint_found BOOLEAN;
    available_status TEXT;
    unsupported_seats TEXT;
    row_plan RECORD;
    report_row RECORD;
    show_id_value BIGINT;
    matching_count BIGINT;
    physical_seat_count BIGINT;
    linked_seat_count BIGINT;
    inserted_seat_count BIGINT;
    is_new_show BOOLEAN;
    new_show_count BIGINT := 0;
    reused_show_count BIGINT := 0;
    new_show_seat_count BIGINT := 0;
    skipped_screen_count BIGINT;
    historical_overlap_count BIGINT;
BEGIN
    -- Required source columns/types: validate the real schema, never migrate it.
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='movies' AND column_name='id' AND data_type='bigint')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='movies' AND column_name='title' AND data_type='text')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='movies' AND column_name='duration_minutes' AND data_type='integer')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='movies' AND column_name='language' AND data_type='text') THEN
        RAISE EXCEPTION 'Movie schema mismatch: expected movies(id bigint,title text,duration_minutes integer,language text).';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='screens' AND column_name='id' AND data_type='bigint')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='seats' AND column_name='screen_id' AND data_type='bigint')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='shows' AND column_name='start_time' AND data_type='timestamp with time zone')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='shows' AND column_name='end_time' AND data_type='timestamp with time zone')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='shows' AND column_name='language' AND data_type='text')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='shows' AND column_name='format' AND data_type='text')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='show_seats' AND column_name='price' AND data_type='numeric')
       OR NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='show_seats' AND column_name='status' AND data_type='text') THEN
        RAISE EXCEPTION 'Screen, seat, show, or show_seats schema does not match the inspected Supabase schema.';
    END IF;

    -- Inserted IDs must be generated by existing identity/default definitions.
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name IN ('shows','show_seats') AND column_name='id'
          AND is_identity <> 'YES' AND column_default IS NULL
    ) THEN
        RAISE EXCEPTION 'shows.id and show_seats.id must be database-generated identity/sequence columns.';
    END IF;

    -- Primary keys and foreign keys required for all joins and inserts.
    FOR required_pk IN SELECT unnest(ARRAY['cities','theatres','screens','seats','movies','shows','show_seats']::text[]) AS table_name
    LOOP
        SELECT attnum INTO source_attnum FROM pg_attribute
        WHERE attrelid=format('public.%I',required_pk.table_name)::regclass AND attname='id' AND NOT attisdropped;
        IF source_attnum IS NULL OR NOT EXISTS (
            SELECT 1 FROM pg_constraint c
            WHERE c.contype='p' AND c.conrelid=format('public.%I',required_pk.table_name)::regclass
              AND c.conkey=ARRAY[source_attnum]::smallint[]
        ) THEN
            RAISE EXCEPTION 'Required single-column primary key public.%.id is missing.',required_pk.table_name;
        END IF;
    END LOOP;

    FOR required_fk IN SELECT * FROM (VALUES
        ('shows','movie_id','movies','id'), ('shows','screen_id','screens','id'),
        ('show_seats','show_id','shows','id'), ('show_seats','seat_id','seats','id'),
        ('seats','screen_id','screens','id'), ('screens','theatre_id','theatres','id'),
        ('theatres','city_id','cities','id')
    ) AS f(source_table,source_column,target_table,target_column)
    LOOP
        SELECT attnum INTO source_attnum FROM pg_attribute
        WHERE attrelid=format('public.%I',required_fk.source_table)::regclass AND attname=required_fk.source_column AND NOT attisdropped;
        SELECT attnum INTO target_attnum FROM pg_attribute
        WHERE attrelid=format('public.%I',required_fk.target_table)::regclass AND attname=required_fk.target_column AND NOT attisdropped;
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint c
            WHERE c.contype='f' AND c.convalidated
              AND c.conrelid=format('public.%I',required_fk.source_table)::regclass
              AND c.confrelid=format('public.%I',required_fk.target_table)::regclass
              AND c.conkey=ARRAY[source_attnum]::smallint[] AND c.confkey=ARRAY[target_attnum]::smallint[]
        ) THEN
            RAISE EXCEPTION 'Required FK public.%(%) -> public.%(%) is missing.',
                required_fk.source_table,required_fk.source_column,required_fk.target_table,required_fk.target_column;
        END IF;
    END LOOP;

    -- These are the unique keys this script relies on. The show-seat key backs
    -- ON CONFLICT; the seat key makes each physical seat address unambiguous.
    FOR required_unique IN SELECT * FROM (VALUES
        ('seats',ARRAY['screen_id','row_label','seat_number']::text[]),
        ('show_seats',ARRAY['show_id','seat_id']::text[])
    ) AS u(table_name,column_names)
    LOOP
        SELECT EXISTS (
            SELECT 1 FROM pg_index i
            WHERE i.indrelid=format('public.%I',required_unique.table_name)::regclass
              AND i.indisunique AND i.indisvalid AND i.indisready AND i.indpred IS NULL AND i.indexprs IS NULL
              AND i.indnkeyatts=cardinality(required_unique.column_names)
              AND ARRAY(
                  SELECT a.attname::text
                  FROM unnest(i.indkey) WITH ORDINALITY AS key_column(attnum,ordinality)
                  JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=key_column.attnum
                  WHERE key_column.ordinality<=i.indnkeyatts ORDER BY key_column.ordinality
              )=required_unique.column_names
        ) INTO constraint_found;
        IF NOT constraint_found THEN
            RAISE EXCEPTION 'Missing required unique key public.%(%) for safe seat/show_seat handling.',
                required_unique.table_name,required_unique.column_names;
        END IF;
    END LOOP;

    -- Resolve all seven existing movies by exact title, and reject ambiguity,
    -- missing runtime/language, or any pre-existing broken movie/screen links.
    IF EXISTS (
        SELECT wanted.title FROM unnest(expected_movies) AS wanted(title)
        LEFT JOIN public.movies m ON m.title=wanted.title
        GROUP BY wanted.title HAVING count(m.id)<>1
    ) THEN
        RAISE EXCEPTION 'Every expected movie title must resolve to exactly one public.movies row.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.movies WHERE title=ANY(expected_movies) AND (duration_minutes IS NULL OR duration_minutes<=0 OR language IS NULL OR btrim(language)='')) THEN
        RAISE EXCEPTION 'A required movie has missing/invalid duration_minutes or language.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.shows sh LEFT JOIN public.movies m ON m.id=sh.movie_id
        LEFT JOIN public.screens sc ON sc.id=sh.screen_id
        WHERE m.id IS NULL OR sc.id IS NULL OR sh.end_time<=sh.start_time
    ) THEN RAISE EXCEPTION 'An existing show has a broken movie/screen link or invalid time interval.'; END IF;
    IF EXISTS (
        SELECT 1 FROM public.show_seats ss LEFT JOIN public.shows sh ON sh.id=ss.show_id
        LEFT JOIN public.seats seat ON seat.id=ss.seat_id
        WHERE sh.id IS NULL OR seat.id IS NULL OR seat.screen_id<>sh.screen_id
    ) THEN RAISE EXCEPTION 'An existing show_seats row references a missing or wrong-screen seat.'; END IF;

    SELECT status::text INTO available_status FROM public.show_seats
    WHERE lower(status::text)='available' ORDER BY status::text LIMIT 1;
    IF available_status IS NULL THEN RAISE EXCEPTION 'No existing AVAILABLE show_seats status convention was found.'; END IF;

    SELECT string_agg(DISTINCT seat_type,', ' ORDER BY seat_type) INTO unsupported_seats
    FROM public.seats WHERE upper(seat_type) NOT IN ('REGULAR','PREMIUM','RECLINER');
    IF unsupported_seats IS NOT NULL THEN
        RAISE EXCEPTION 'Unsupported seat_type(s) need explicit seed pricing: %.', unsupported_seats;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.screens) OR EXISTS (
        SELECT 1 FROM public.screens sc LEFT JOIN public.seats seat ON seat.screen_id=sc.id
        GROUP BY sc.id HAVING count(seat.id)=0
    ) THEN RAISE EXCEPTION 'Every existing screen must have at least one seat before generating shows.'; END IF;

    -- Keep generated time slots deterministic. Each screen gets the same movie
    -- rotation; each title appears three times in the seven-day window.
    CREATE TEMP TABLE _dev_schedule_movies ON COMMIT DROP AS
    SELECT m.id AS movie_id,m.title,m.duration_minutes,m.language,
           array_position(expected_movies,m.title) AS movie_order
    FROM public.movies m WHERE m.title=ANY(expected_movies);

    CREATE TEMP TABLE _dev_schedule_plan ON COMMIT DROP AS
    WITH day_rows AS (
        SELECT d::date AS show_date,
               (row_number() OVER (ORDER BY d)-1)::integer AS day_index
        FROM generate_series(date '2026-11-11',date '2026-11-17',interval '1 day') AS d
    ), slots AS (
        SELECT * FROM (VALUES (1,time '10:00'),(2,time '14:00'),(3,time '18:00')) AS x(slot_index,local_start)
    ), candidates AS (
        SELECT sc.id AS screen_id,day_rows.show_date,day_rows.day_index,slots.slot_index,slots.local_start,
               (((day_rows.day_index*3+slots.slot_index-1)%7)+1)::integer AS movie_order
        FROM public.screens sc CROSS JOIN day_rows CROSS JOIN slots
    )
    SELECT candidates.screen_id,m.movie_id,m.title AS movie_title,m.language,m.duration_minutes,
           candidates.show_date,candidates.slot_index,candidates.local_start,
           ((candidates.show_date+candidates.local_start) AT TIME ZONE 'Asia/Kolkata') AS start_time,
           ((candidates.show_date+candidates.local_start) AT TIME ZONE 'Asia/Kolkata')
               + make_interval(mins=>m.duration_minutes) AS end_time,
           '2D'::text AS show_format
    FROM candidates JOIN _dev_schedule_movies m ON m.movie_order=candidates.movie_order;

    ALTER TABLE _dev_schedule_plan ADD PRIMARY KEY (screen_id,start_time);

    IF EXISTS (
        SELECT 1 FROM _dev_schedule_plan a JOIN _dev_schedule_plan b
          ON b.screen_id=a.screen_id AND b.start_time>a.start_time
         AND a.start_time < b.end_time+interval '30 minutes'
         AND a.end_time+interval '30 minutes' > b.start_time
    ) THEN RAISE EXCEPTION 'Generated schedule has overlapping shows or less than 30 minutes cleaning time.'; END IF;

    -- Only conflicts that intersect the target window skip a screen. The
    -- October records are historical; they remain untouched and do not block
    -- the November schedule. Exact matching rows are eligible for rerun reuse.
    CREATE TEMP TABLE _dev_skipped_screens ON COMMIT DROP AS
    SELECT DISTINCT p.screen_id
    FROM _dev_schedule_plan p JOIN public.shows existing ON existing.screen_id=p.screen_id
      AND existing.start_time < p.end_time+interval '30 minutes'
      AND existing.end_time > p.start_time-interval '30 minutes'
    WHERE NOT (
        existing.movie_id=p.movie_id AND existing.start_time=p.start_time AND existing.end_time=p.end_time
        AND existing.language=p.language AND existing.format=p.show_format
    );

    SELECT count(*) INTO historical_overlap_count
    FROM public.shows a JOIN public.shows b ON b.screen_id=a.screen_id AND b.id>a.id
      AND a.start_time<b.end_time AND a.end_time>b.start_time
    WHERE a.end_time < (date '2026-11-11' AT TIME ZONE 'Asia/Kolkata');
    IF historical_overlap_count>0 THEN
        RAISE NOTICE 'Existing historical overlaps found: % pair(s); they are preserved and outside the new schedule window.', historical_overlap_count;
    END IF;

    SELECT count(*) INTO skipped_screen_count FROM _dev_skipped_screens;
    FOR report_row IN
        SELECT sc.id,sc.name,th.name AS theatre_name
        FROM _dev_skipped_screens skipped JOIN public.screens sc ON sc.id=skipped.screen_id
        JOIN public.theatres th ON th.id=sc.theatre_id ORDER BY th.name,sc.name
    LOOP
        RAISE NOTICE 'Screen skipped due to schedule conflict: screen % (%), theatre %.',
            report_row.id,report_row.name,report_row.theatre_name;
    END LOOP;

    FOR row_plan IN
        SELECT p.* FROM _dev_schedule_plan p
        WHERE NOT EXISTS (SELECT 1 FROM _dev_skipped_screens s WHERE s.screen_id=p.screen_id)
        ORDER BY p.screen_id,p.start_time
    LOOP
        SELECT count(*),min(id) INTO matching_count,show_id_value
        FROM public.shows WHERE screen_id=row_plan.screen_id AND start_time=row_plan.start_time;
        IF matching_count>1 THEN
            RAISE EXCEPTION 'Duplicate existing shows occupy screen % at %; transaction aborted.',row_plan.screen_id,row_plan.start_time;
        ELSIF matching_count=1 THEN
            IF NOT EXISTS (
                SELECT 1 FROM public.shows WHERE id=show_id_value AND movie_id=row_plan.movie_id
                  AND end_time=row_plan.end_time AND language=row_plan.language AND format=row_plan.show_format
            ) THEN
                RAISE EXCEPTION 'Existing show % at % does not match the generated slot; no existing row was changed.',show_id_value,row_plan.start_time;
            END IF;
            reused_show_count:=reused_show_count+1;
            is_new_show:=false;
        ELSE
            INSERT INTO public.shows(movie_id,screen_id,start_time,end_time,language,format)
            VALUES(row_plan.movie_id,row_plan.screen_id,row_plan.start_time,row_plan.end_time,row_plan.language,row_plan.show_format)
            RETURNING id INTO show_id_value;
            new_show_count:=new_show_count+1;
            is_new_show:=true;
        END IF;

        SELECT count(*) INTO physical_seat_count FROM public.seats WHERE screen_id=row_plan.screen_id;
        IF is_new_show THEN
            INSERT INTO public.show_seats(show_id,seat_id,price,status)
            SELECT show_id_value,seat.id,
                   (CASE upper(seat.seat_type)
                        WHEN 'REGULAR' THEN 180
                        WHEN 'PREMIUM' THEN 250
                        WHEN 'RECLINER' THEN 350
                    END + CASE WHEN row_plan.slot_index=3 THEN 30 ELSE 0 END)::numeric,
                   available_status
            FROM public.seats seat
            WHERE seat.screen_id=row_plan.screen_id
            ON CONFLICT(show_id,seat_id) DO NOTHING;
            GET DIAGNOSTICS inserted_seat_count=ROW_COUNT;
            new_show_seat_count:=new_show_seat_count+inserted_seat_count;
        END IF;

        SELECT count(*) INTO linked_seat_count FROM public.show_seats WHERE show_id=show_id_value;
        IF linked_seat_count<>physical_seat_count OR EXISTS (
            SELECT 1 FROM public.show_seats ss JOIN public.seats seat ON seat.id=ss.seat_id
            WHERE ss.show_id=show_id_value AND seat.screen_id<>row_plan.screen_id
        ) THEN
            RAISE EXCEPTION 'Show % has % show_seats for % physical seats, or a wrong-screen seat; transaction rolled back.',
                show_id_value,linked_seat_count,physical_seat_count;
        END IF;
    END LOOP;

    RAISE NOTICE 'Development schedule transaction summary: % new shows, % exact existing shows reused, % new show_seats, % screens skipped.',
        new_show_count,reused_show_count,new_show_seat_count,skipped_screen_count;
    FOR report_row IN
        SELECT p.movie_title,p.show_date,count(*) AS show_count
        FROM _dev_schedule_plan p
        WHERE NOT EXISTS (SELECT 1 FROM _dev_skipped_screens s WHERE s.screen_id=p.screen_id)
        GROUP BY p.movie_title,p.show_date ORDER BY p.show_date,p.movie_title
    LOOP
        RAISE NOTICE 'Planned slots: % | % | % show(s).',report_row.show_date,report_row.movie_title,report_row.show_count;
    END LOOP;
END $$;

COMMIT;

-- Post-run verification (the first-run totals above apply to the inspected
-- one-screen database; reruns will report reused rows and zero additional seats).
SELECT m.title,(sh.start_time AT TIME ZONE 'Asia/Kolkata')::date AS show_date,
       count(DISTINCT sh.id) AS show_count,
       min(sh.start_time AT TIME ZONE 'Asia/Kolkata')::time AS first_local_start,
       max(sh.start_time AT TIME ZONE 'Asia/Kolkata')::time AS last_local_start,
       min(seat_count.expected_seats) AS physical_seats_per_screen,
       min(seat_count.actual_show_seats) AS minimum_show_seats
FROM public.shows sh
JOIN public.movies m ON m.id=sh.movie_id
JOIN public.screens sc ON sc.id=sh.screen_id
CROSS JOIN LATERAL (
    SELECT count(DISTINCT seat.id) AS expected_seats,
           count(DISTINCT ss.seat_id) AS actual_show_seats
    FROM public.seats seat LEFT JOIN public.show_seats ss ON ss.seat_id=seat.id AND ss.show_id=sh.id
    WHERE seat.screen_id=sh.screen_id
) seat_count
WHERE sh.start_time >= date '2026-11-11' AT TIME ZONE 'Asia/Kolkata'
  AND sh.start_time < (date '2026-11-18' AT TIME ZONE 'Asia/Kolkata')
GROUP BY m.title,(sh.start_time AT TIME ZONE 'Asia/Kolkata')::date
ORDER BY show_date,m.title;

-- Conflict check for the generated week; expected to return no rows.
SELECT a.screen_id,a.id AS first_show_id,b.id AS second_show_id,a.start_time,a.end_time,b.start_time,b.end_time
FROM public.shows a JOIN public.shows b ON b.screen_id=a.screen_id AND b.id>a.id
 AND a.start_time < b.end_time+interval '30 minutes'
 AND a.end_time+interval '30 minutes' > b.start_time
WHERE a.start_time >= date '2026-11-11' AT TIME ZONE 'Asia/Kolkata'
  AND a.start_time < date '2026-11-18' AT TIME ZONE 'Asia/Kolkata'
  AND b.start_time >= date '2026-11-11' AT TIME ZONE 'Asia/Kolkata'
  AND b.start_time < date '2026-11-18' AT TIME ZONE 'Asia/Kolkata';
